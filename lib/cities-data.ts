// Normalise diacritics + lowercase for fuzzy matching
function norm(s: string) {
  return s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase();
}

export function searchCities(query: string, limit = 6): City[] {
  if (query.length < 2) return [];
  const q = norm(query);
  const results: Array<{ city: City; score: number }> = [];

  for (const city of CITIES) {
    const names = [city.name, ...(city.alt ?? [])];
    let best = 0;
    for (const n of names) {
      const normalised = norm(n);
      if (normalised === q) { best = 3; break; }
      if (normalised.startsWith(q)) { best = Math.max(best, 2); }
      else if (normalised.includes(q)) { best = Math.max(best, 1); }
    }
    if (best > 0) results.push({ city, score: best });
  }

  return results
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((r) => r.city);
}
